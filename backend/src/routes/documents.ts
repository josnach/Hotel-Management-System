
import { Router, type Request, type Response, type NextFunction } from 'express';
import multer from 'multer';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { mkdir, unlink, open } from 'node:fs/promises';

import { prisma } from '../lib/prisma';
import { HttpError } from '../lib/http';

export const documentsRouter = Router();

const MAX_FILE_SIZE = 10 * 1024 * 1024;

const STORAGE_DIR = path.resolve(
  process.env.HMS_DOCUMENT_STORAGE_DIR ||
    path.join(process.cwd(), 'private-documents'),
);

const ALLOWED_TYPES: Record<string, string> = {
  '.pdf': 'application/pdf',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
};

async function validateDocumentSignature(
  filePath: string,
  expectedMimeType: string,
): Promise<boolean> {
  const handle = await open(filePath, 'r');

  try {
    const header = Buffer.alloc(8);
    const { bytesRead } = await handle.read(header, 0, 8, 0);
    const bytes = header.subarray(0, bytesRead);

    if (expectedMimeType === 'application/pdf') {
      return bytes.length >= 5 && bytes.subarray(0, 5).toString() === '%PDF-';
    }

    if (expectedMimeType === 'image/jpeg') {
      return (
        bytes.length >= 3 &&
        bytes[0] === 0xff &&
        bytes[1] === 0xd8 &&
        bytes[2] === 0xff
      );
    }

    if (expectedMimeType === 'image/png') {
      return (
        bytes.length >= 8 &&
        bytes.equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))
      );
    }

    return false;
  } finally {
    await handle.close();
  }
}

const ALLOWED_CATEGORIES = [
  'GUEST_ID',
  'PASSPORT',
  'SIGNED_AGREEMENT',
  'CONTRACT',
  'OTHER',
] as const;

type DocumentCategory = (typeof ALLOWED_CATEGORIES)[number];

function canManageDocuments(role: string): boolean {
  return role === 'ADMIN' || role === 'MANAGER';
}

function canUseDocuments(role: string): boolean {
  return (
    role === 'ADMIN' ||
    role === 'MANAGER' ||
    role === 'RECEPTIONIST'
  );
}

function requireDocumentAccess(req: Request): void {
  const user = (req as Request & {
    user?: { id?: string; role?: string };
  }).user;

  if (!user?.id || !user?.role) {
    throw new HttpError(401, 'Authentication required');
  }

  if (!canUseDocuments(user.role)) {
    throw new HttpError(403, 'You cannot access guest documents');
  }
}

/**
 * Authorization middleware must run before Multer.
 * This prevents unauthorized requests from writing uploaded files.
 */
function documentAccessMiddleware(
  req: Request,
  _res: Response,
  next: NextFunction,
): void {
  try {
    requireDocumentAccess(req);
    next();
  } catch (error) {
    next(error);
  }
}

const storage = multer.diskStorage({
  destination: (_req, _file, callback) => {
    mkdir(STORAGE_DIR, { recursive: true })
      .then(() => callback(null, STORAGE_DIR))
      .catch((error) => callback(error as Error, STORAGE_DIR));
  },

  filename: (_req, file, callback) => {
    const extension = path.extname(file.originalname).toLowerCase();
    callback(null, `${randomUUID()}${extension}`);
  },
});

const upload = multer({
  storage,
  limits: {
    fileSize: MAX_FILE_SIZE,
    files: 1,
  },
  fileFilter: (_req, file, callback) => {
    const extension = path.extname(file.originalname).toLowerCase();
    const expectedMimeType = ALLOWED_TYPES[extension];

    if (!expectedMimeType || file.mimetype !== expectedMimeType) {
      callback(
        new HttpError(
          400,
          'Only PDF, JPEG, and PNG documents are allowed',
        ),
      );
      return;
    }

    callback(null, true);
  },
});

function safeStoredPath(storageKey: string): string {
  // Storage keys are generated by the server. Never accept a client path.
  if (
    path.basename(storageKey) !== storageKey ||
    !/^[0-9a-f-]+\.(pdf|jpg|jpeg|png)$/i.test(storageKey)
  ) {
    throw new HttpError(400, 'Invalid document storage key');
  }

  return path.join(STORAGE_DIR, storageKey);
}

documentsRouter.get('/', async (req, res, next) => {
  try {
    requireDocumentAccess(req);

    const guestId =
      typeof req.query.guestId === 'string'
        ? req.query.guestId.trim()
        : '';

    if (!guestId) {
      throw new HttpError(400, 'guestId is required');
    }

    const documents = await prisma.guestDocument.findMany({
      where: { guestId },
      orderBy: { createdAt: 'desc' },
      select: {
        id: true,
        guestId: true,
        uploadedById: true,
        category: true,
        originalName: true,
        mimeType: true,
        sizeBytes: true,
        notes: true,
        createdAt: true,
        uploadedBy: {
          select: { id: true, fullName: true, username: true },
        },
      },
    });

    res.json({ documents });
  } catch (error) {
    next(error);
  }
});

documentsRouter.post(
  '/',
  documentAccessMiddleware,
  upload.single('file'),
  async (req, res, next) => {
    try {
      // Authorization has already completed before Multer processes the file.
      const user = (req as Request & {
        user: { id: string; role: string };
      }).user;

      const file = req.file;

      if (!file) {
        throw new HttpError(400, 'Select a document to upload');
      }

      const extension = path.extname(file.originalname).toLowerCase();
const expectedMimeType = ALLOWED_TYPES[extension];

if (
  !expectedMimeType ||
  file.mimetype !== expectedMimeType ||
  !(await validateDocumentSignature(file.path, expectedMimeType))
) {
  await unlink(file.path).catch(() => undefined);

  throw new HttpError(
    400,
    'The uploaded file content does not match an allowed document type',
  );
}

      const guestId =
        typeof req.body.guestId === 'string'
          ? req.body.guestId.trim()
          : '';

      const category =
        typeof req.body.category === 'string'
          ? req.body.category.trim()
          : '';

      const notes =
        typeof req.body.notes === 'string'
          ? req.body.notes.trim()
          : '';

      if (!guestId) {
        await unlink(file.path).catch(() => undefined);
        throw new HttpError(400, 'guestId is required');
      }

      if (
        !ALLOWED_CATEGORIES.includes(category as DocumentCategory)
      ) {
        await unlink(file.path).catch(() => undefined);
        throw new HttpError(400, 'Invalid document category');
      }

      if (notes.length > 1000) {
        await unlink(file.path).catch(() => undefined);
        throw new HttpError(400, 'Notes cannot exceed 1000 characters');
      }

      const guest = await prisma.guest.findUnique({
        where: { id: guestId },
        select: { id: true },
      });

      if (!guest) {
        await unlink(file.path).catch(() => undefined);
        throw new HttpError(404, 'Guest not found');
      }

      try {
        const document = await prisma.guestDocument.create({
          data: {
            guestId,
            uploadedById: user.id,
            category: category as DocumentCategory,
            originalName: path.basename(file.originalname).slice(0, 255),
            storageKey: file.filename,
            mimeType: file.mimetype,
            sizeBytes: file.size,
            notes: notes || null,
          },
          select: {
            id: true,
            guestId: true,
            uploadedById: true,
            category: true,
            originalName: true,
            mimeType: true,
            sizeBytes: true,
            notes: true,
            createdAt: true,
          },
        });

        res.status(201).json({ document });
      } catch (error) {
        await unlink(file.path).catch(() => undefined);
        throw error;
      }
    } catch (error) {
      next(error);
    }
  },
);

documentsRouter.get('/:id/download', async (req, res, next) => {
  try {
    requireDocumentAccess(req);

    const document = await prisma.guestDocument.findUnique({
      where: { id: req.params.id },
      select: {
        id: true,
        storageKey: true,
        originalName: true,
        mimeType: true,
      },
    });

    if (!document) {
      throw new HttpError(404, 'Document not found');
    }

    const filePath = safeStoredPath(document.storageKey);

    res.setHeader('X-Content-Type-Options', 'nosniff');
    res.setHeader('Content-Type', 'application/octet-stream');

    res.download(filePath, document.originalName, (error) => {
      if (error && !res.headersSent) {
        next(error);
      }
    });
  } catch (error) {
    next(error);
  }
});

documentsRouter.delete('/:id', async (req, res, next) => {
  try {
    requireDocumentAccess(req);

    const user = (req as Request & {
      user: { id: string; role: string };
    }).user;

    if (!canManageDocuments(user.role)) {
      throw new HttpError(
        403,
        'Only an administrator or manager can delete documents',
      );
    }

    const document = await prisma.guestDocument.findUnique({
      where: { id: req.params.id },
      select: { id: true, storageKey: true },
    });

    if (!document) {
      throw new HttpError(404, 'Document not found');
    }

    // Remove the metadata first. If deleting the file fails, the private
    // storage directory can be reconciled without exposing the file publicly.
    await prisma.guestDocument.delete({
      where: { id: document.id },
    });

    await unlink(safeStoredPath(document.storageKey)).catch(
      (error: NodeJS.ErrnoException) => {
        if (error.code !== 'ENOENT') {
          console.error('Unable to remove private document file');
        }
      },
    );

    res.json({ ok: true });
  } catch (error) {
    next(error);
  }
});
